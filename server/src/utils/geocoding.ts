export async function geocodeTerritory(query: string): Promise<{ lat: number; lng: number } | null> {
    if (!query || !query.trim()) {
        return null;
    }
    const q = query.trim();
    const key = q.toLowerCase();

    // 1. Перевіряємо fallback для загальних/неоднозначних територій.
    if (FALLBACK_COORDINATES[key]) {
        return { ...FALLBACK_COORDINATES[key] };
    }

    // 2. Спробуємо спочатку як країну, потім загальний пошук.
    const candidates = await Promise.all([
        tryGeocode(q, 'country'),
        tryGeocode(q)
    ]);

    for (const data of candidates) {
        if (!data) continue;
        const best = data.find((item: any) =>
            item.type === 'country' ||
            item.type === 'administrative' ||
            item.class === 'boundary' ||
            item.class === 'place' && item.type === 'country'
        );
        if (best) {
            const lat = parseFloat(best.lat);
            const lng = parseFloat(best.lon);
            if (!isNaN(lat) && !isNaN(lng)) {
                return { lat, lng };
            }
        }
        const first = data[0];
        if (first) {
            const lat = parseFloat(first.lat);
            const lng = parseFloat(first.lon);
            if (!isNaN(lat) && !isNaN(lng)) {
                return { lat, lng };
            }
        }
    }

    return null;
}

async function tryGeocode(q: string, featureType?: string): Promise<any[] | null> {
    let url = `https://nominatim.openstreetmap.org/search?format=jsonv2&q=${encodeURIComponent(q)}&limit=10&accept-language=uk,en`;
    if (featureType) {
        url += `&featuretype=${featureType}`;
    }
    try {
        const response = await axios.get(url, {
            timeout: 10000,
            headers: {
                'User-Agent': 'Mozilla/5.0 (compatible; WeaponryEncyclopedia/1.0; +https://example.com)',
                'Accept-Language': 'uk,en;q=0.9',
                'Referer': 'https://example.com/'
            }
        });
        const data = response.data;
        if (Array.isArray(data) && data.length > 0) {
            return data;
        }
    } catch (error) {
        console.error('Geocoding error for query', q, featureType, error);
    }
    return null;
}
